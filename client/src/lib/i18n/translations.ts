export const catalogs: Record<AppLanguage, TranslationCatalog> = { en, he };

export function translate(
  language: AppLanguage,
  key: string,
  params: Record<string, string> | undefined,
): string {
  const template = catalogs[language][key] ?? catalogs.en[key] ?? key;
  if (params === undefined) {
    return template;
  }
  return Object.entries(params).reduce(
    (result, [paramKey, paramValue]) => result.replace(`{{${paramKey}}}`, paramValue),
    template,
  );
}
